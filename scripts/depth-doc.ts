// Renders docs/DEPTH.md from the measured report. Every number in that file comes from reports/claim-sizes.json.
import { resolve } from 'node:path';
import { REPO_ROOT } from '../src/config.ts';

export const DEPTH_DOC_PATH = resolve(REPO_ROOT, 'docs/DEPTH.md');
/** Consensus limit on the unlocking bytecode of one input (BCH 2025 VM limits). */
export const MAX_UNLOCKING_BYTES = 10_000;

export interface PoolInputUsage {
  unlockingBytes: number;
  operationCost: number;
  maximumOperationCost: number;
  hashDigestIterations: number;
  maximumHashDigestIterations: number;
}

export interface ClaimSizeReport {
  description: string;
  generatedBy: string;
  feeRateSatsPerByte: number;
  contractBytes: Record<string, number>;
  claims: Array<{ depth: number; firstClaimBytes: number; additionalClaimBytes: number; poolInput: PoolInputUsage }>;
  operator: { proposeBytes: number; activateBytes: number };
}

export interface DepthLimits {
  perLevel: { claimBytes: number; unlockingBytes: number; operationCost: number; operationBudget: number; hashes: number; hashBudget: number };
  byUnlockingBytes: number;
  byOperationCost: number | undefined;
  byHashes: number | undefined;
  maxDepth: number;
}

/** Deepest depth at which `used + k * usedStep` stays within `limit + k * limitStep`; undefined when it never runs out. */
function lastDepth(depth: number, used: number, usedStep: number, limit: number, limitStep: number): number | undefined {
  const slackStep = limitStep - usedStep;
  if (slackStep >= 0) return undefined;
  return depth + Math.floor((limit - used) / -slackStep);
}

/** Extrapolates linearly from the two deepest measurements; each proof level adds the same bytes and work. */
export function depthLimits(report: ClaimSizeReport): DepthLimits {
  const [lo, hi] = report.claims.slice(-2);
  if (!lo || !hi || hi.depth <= lo.depth) throw new Error('need two measured depths');
  const levels = hi.depth - lo.depth;
  type Row = ClaimSizeReport['claims'][number];
  const step = (f: (c: Row) => number): number => (f(hi) - f(lo)) / levels;
  const perLevel = {
    claimBytes: step((c) => c.firstClaimBytes),
    unlockingBytes: step((c) => c.poolInput.unlockingBytes),
    operationCost: step((c) => c.poolInput.operationCost),
    operationBudget: step((c) => c.poolInput.maximumOperationCost),
    hashes: step((c) => c.poolInput.hashDigestIterations),
    hashBudget: step((c) => c.poolInput.maximumHashDigestIterations),
  };
  const p = hi.poolInput;
  const byUnlockingBytes = hi.depth + Math.floor((MAX_UNLOCKING_BYTES - p.unlockingBytes) / perLevel.unlockingBytes);
  const byOperationCost = lastDepth(hi.depth, p.operationCost, perLevel.operationCost, p.maximumOperationCost, perLevel.operationBudget);
  const byHashes = lastDepth(hi.depth, p.hashDigestIterations, perLevel.hashes, p.maximumHashDigestIterations, perLevel.hashBudget);
  const maxDepth = Math.min(byUnlockingBytes, byOperationCost ?? Infinity, byHashes ?? Infinity);
  return { perLevel, byUnlockingBytes, byOperationCost, byHashes, maxDepth };
}

const n = (v: number): string => v.toLocaleString('en-US');
const pct = (used: number, max: number): string => `${((used / max) * 100).toFixed(1)}%`;
const limitText = (v: number | undefined): string => (v === undefined ? 'never (the budget grows faster than the use)' : `depth ${n(v)}`);

export function renderDepthDoc(report: ClaimSizeReport): string {
  const limits = depthLimits(report);
  const rows = report.claims.map((c) => {
    const p = c.poolInput;
    return `| ${c.depth} | ${n(2 ** c.depth)} | ${n(c.firstClaimBytes)} | ${n(c.additionalClaimBytes)} | ${n(p.unlockingBytes)} | ` +
      `${n(p.operationCost)} of ${n(p.maximumOperationCost)} (${pct(p.operationCost, p.maximumOperationCost)}) | ` +
      `${n(p.hashDigestIterations)} of ${n(p.maximumHashDigestIterations)} |`;
  });
  const l = limits.perLevel;
  return `# Proof depth and VM limits

Generated by \`npm run claim-sizes\` (\`${report.generatedBy}\`) from \`reports/claim-sizes.json\`; a test fails when
this file and a fresh measurement differ. Do not edit by hand.

A claim proves its leaf with one 32-byte sibling per tree level, so a tree of depth \`d\` holds up to \`2^d\` leaves.
All proof work runs in input 0 (the pool state NFT, \`ClaimPool.claim\`). The 2026 VM gives each input an operation
cost budget and a hash budget that grow with the length of its unlocking bytecode, and caps that unlocking bytecode
at ${n(MAX_UNLOCKING_BYTES)} bytes.

## Measured

${report.description}

| Depth | Leaves | First claim (bytes) | Additional claim (bytes) | Input 0 unlocking (bytes) | Input 0 operation cost | Input 0 hash iterations |
|---|---|---|---|---|---|---|
${rows.join('\n')}

Contract sizes: ${Object.entries(report.contractBytes).map(([k, v]) => `${k} ${n(v)} bytes`).join(', ')}.

## Per extra level (from the two deepest measurements)

- Claim size: +${n(l.claimBytes)} bytes; input 0 unlocking bytecode: +${n(l.unlockingBytes)} bytes.
- Operation cost: +${n(l.operationCost)} used, +${n(l.operationBudget)} budget.
- Hash iterations: +${n(l.hashes)} used, +${n(l.hashBudget)} budget.

## Deepest proof the VM accepts (linear extrapolation)

- Unlocking bytecode limit: depth ${n(limits.byUnlockingBytes)}.
- Operation cost budget: ${limitText(limits.byOperationCost)}.
- Hash budget: ${limitText(limits.byHashes)}.

The binding limit is depth ${n(limits.maxDepth)}. The contract enforces its own \`maxDepth\` parameter
(\`tree.maxDepth\` in \`config/tuai.json\`), which must stay at or below that value; the library and the tests use the
same setting, and a proof one level deeper is rejected on chain.

## Operator cost per epoch

Each epoch costs the operators one propose transaction (${n(report.operator.proposeBytes)} bytes) and one activate
transaction (${n(report.operator.activateBytes)} bytes, which anyone may send). Neither depends on the number of
recipients or on the tree depth.
`;
}
