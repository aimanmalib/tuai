// Renders docs/COST.md from measured inputs only: reports/claim-sizes.json, reports/push-distributions.json and push
// transactions built (not broadcast) by src/cost/push.ts. Run with `npm run cost`; tests/cost.test.ts fails when the
// committed file is stale. Offline.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { REPO_ROOT, loadConfig } from '../src/config.ts';
import { buildCostModel, pushModelFrom, type ClaimSizes, type CostModel, type PushDistributionReport } from '../src/cost/report.ts';
import { pushDistributionBytes } from '../src/cost/push.ts';

export const COST_DOC_PATH = resolve(REPO_ROOT, 'docs/COST.md');
const SATS_PER_BCH = 100_000_000;

const n = (v: number): string => v.toLocaleString('en-US');
const usd = (sats: number, m: CostModel): string => `$${((sats * m.usdPerBch) / SATS_PER_BCH).toFixed(4)}`;
const sat = (sats: number, m: CostModel): string => `${n(sats)} (${usd(sats, m)})`;

export function loadCostInputs() {
  const config = loadConfig();
  const sizes = JSON.parse(readFileSync(resolve(REPO_ROOT, 'reports/claim-sizes.json'), 'utf8')) as ClaimSizes;
  const push = JSON.parse(readFileSync(resolve(REPO_ROOT, config.cost.reportPath), 'utf8')) as PushDistributionReport;
  return { config, sizes, push };
}

export function renderCostDoc(): string {
  const { config, sizes, push } = loadCostInputs();
  const m = buildCostModel(config, sizes, push);
  const model = pushModelFrom(config, m.feeRate);
  const live = push.distributions.map((d) => {
    const rebuilt = d.inputs === 1 ? n(pushDistributionBytes(d.recipients, model)) : 'not modelled (2 inputs)';
    return `| ${d.blockTimeUtc.slice(0, 10)} | ${n(d.blockHeight)} | \`${d.txid}\` | ${d.inputs} | ${d.recipients} | ${n(d.bytes)} | ${rebuilt} | ${n(d.feeSats)} | ${n(d.dustSats)} |`;
  });
  const operator = m.rows.map((r) =>
    `| ${n(r.recipients)} | ${r.push.transactions} | ${n(r.push.bytes)} | ${n(r.push.feeSats)} | ${n(r.push.dustSats)} | ` +
    `${sat(r.pushSats, m)} | ${sat(r.pullOperatorSats, m)} | ${sat(r.pushSats * m.epochsPerYear, m)} | ${sat(r.pullOperatorSats * m.epochsPerYear, m)} |`);
  const user = m.rows.map((r) =>
    `| ${n(r.recipients)} | ${r.depth} | ${n(r.firstClaimBytes)} | ${sat(r.firstClaimSats, m)} | ${n(r.additionalClaimBytes)} | ` +
    `${sat(r.additionalClaimSats, m)} | ${n(r.paymentDustSats)} | ${sat(r.pushPerRecipientSats, m)} | ${r.breakEvenClaimIntervalEpochs} |`);
  return `# Cost: pull claims compared with push distributions

Generated by \`npm run cost\` (\`scripts/cost.ts\`); a test fails when this file and a fresh render differ. Do not edit
by hand. Inputs: \`reports/claim-sizes.json\` (claim and root-gate sizes measured on the mock network),
\`${config.cost.reportPath}\` (live mainnet distributions and the BCH price, measured by \`npm run push-measure\`) and
push transactions built, signed and measured by \`src/cost/push.ts\` (built, not broadcast).

Fee rate ${m.feeRate} sat per byte. Dust ${n(config.fees.tokenOutputDustSats)} sat per token output, receipt dust
${n(config.fees.receiptDustSats)} sat. Price ${push.price.usdPerBch} USD per BCH, measured ${push.price.measuredAtUtc}
from \`${push.price.source}\`. One epoch is one distribution; ${m.epochsPerYear} epochs per year.

## Live push distributions on mainnet

The sponsor's distribution script sends one transaction per epoch: output 0 returns BCH change to the distributor and
each recipient gets one output with ${n(config.fees.tokenOutputDustSats)} sat of dust and their tokens. These are every
transaction of that shape found for the reward token (${push.candidatesChecked} candidate transactions checked,
measured ${push.measuredAtUtc}, indexer \`${push.indexer}\`, transactions and spent outputs read from Electrum
\`${push.electrum}\`). The "rebuilt" column is the size of the same layout built by \`src/cost/push.ts\`; it matches
the live size, so the builder is used for the larger recipient counts below.

| Block date (UTC) | Height | Transaction | Inputs | Recipients | Bytes | Rebuilt bytes | Fee (sat) | Dust (sat) |
|---|---|---|---|---|---|---|---|---|
${live.join('\n')}

## Distributor cost per epoch

Push: the distributor pays the fee and the dust of every recipient output, every epoch, including recipients who never
use the tokens. A standard transaction holds at most ${n(m.maxRecipientsPerTx)} recipients (${n(m.maxStandardTxBytes)}
bytes), so larger distributions are split into several transactions. Pull: the operators pay one propose and one
activate transaction per epoch, whatever the number of recipients.

| Recipients | Push txs | Push bytes | Push fee | Push dust | Push total, sat (USD) | Pull total, sat (USD) | Push per year | Pull per year |
|---|---|---|---|---|---|---|---|---|
${operator.join('\n')}

Push costs the distributor more than pull from ${n(m.operatorBreakEvenRecipients)} recipients per epoch.

## Recipient cost per claim

Pull moves the per-recipient cost to the recipient, who claims only when it suits them. The first claim also pays
the receipt dust that stays in the pool; later claims update that receipt. The payment output's dust stays with the
claimant (it is their own output). The tree depth is the smallest that holds the recipient count.

| Recipients | Tree depth | First claim bytes | First claim fee + receipt, sat (USD) | Later claim bytes | Later claim fee, sat (USD) | Payment dust, sat | Push cost per recipient per epoch, sat (USD) | Break-even claim interval (epochs) |
|---|---|---|---|---|---|---|---|---|
${user.join('\n')}

Break-even claim interval: a recipient who claims once every this many epochs (or less often) costs the network no more
in fees and dust than the pushes the claim replaces, because one claim collects the whole cumulative amount. Counted on
both sides: the fee and the one dust output the recipient receives.

## Reading the numbers

- Push is cheaper per transaction for very small, always-active recipient lists, which matches the live distributions
  above.
- Pull keeps the distributor's cost flat as the recipient list grows, never spends dust on recipients who do not
  claim, and has no minimum payout, at the price of a larger claim transaction paid by the claimant.
- Sizes come from the measured reports; rerun \`npm run claim-sizes\` after contract changes, \`npm run push-measure\`
  to refresh live data and price, then \`npm run cost\`.
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(REPO_ROOT, 'scripts/cost.ts')) {
  writeFileSync(COST_DOC_PATH, renderCostDoc());
  console.log(`wrote ${COST_DOC_PATH}`);
}
